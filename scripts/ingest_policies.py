"""One-off ingestion: store-policy PDF -> data/processed/policies.md (one '##' per top-level section).

Why a pre-processing step instead of reading the PDF at runtime:
- pypdf's default extraction returns one word per line for this file; 'layout' mode keeps
  the tables readable, but page headers/footers still need to be removed.
- The manual is small and changes rarely, so a reviewed, version-controlled Markdown file is the
  most reliable "source of truth" for the agent and is easy to diff when the manual changes.

Usage:  python scripts/ingest_policies.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / "data" / "raw" / "politicas_da_loja.pdf"
OUT = ROOT / "data" / "processed" / "policies.md"

HEADER_RE = re.compile(r"^\s*Empório da Música Manual de Políticas e Procedimentos\s*$")
FOOTER_RE = re.compile(r"^\s*Página \d+\s*$")
SECTION_RE = re.compile(r"^(\d{1,2})\.\s+(\S.*)$")  # "4. Política de Trocas e Devoluções"


def extract_lines(pdf_path: Path) -> list[str]:
    reader = PdfReader(pdf_path)
    lines: list[str] = []
    for page in reader.pages[1:]:  # page 1 is the cover
        for line in page.extract_text(extraction_mode="layout").splitlines():
            if HEADER_RE.match(line) or FOOTER_RE.match(line):
                continue
            lines.append(line.rstrip().replace("•​", "-").replace("​", ""))
    return lines


def split_sections(lines: list[str]) -> list[tuple[str, str, str]]:
    sections: list[tuple[str, str, list[str]]] = []
    for line in lines:
        m = SECTION_RE.match(line.strip())
        if m and not line.startswith(" "):
            sections.append((m.group(1), m.group(2).strip(), []))
        elif sections:
            sections[-1][2].append(line)
    out = []
    for num, title, body in sections:
        text = re.sub(r"\n{3,}", "\n\n", "\n".join(body)).strip("\n")
        out.append((num, title, text))
    return out


def main() -> int:
    sections = split_sections(extract_lines(PDF))
    if len(sections) < 10:
        print(f"Expected 10 sections, found {len(sections)}", file=sys.stderr)
        return 1
    parts = [
        "# Empório da Música — Manual de Políticas e Procedimentos (v2.1, jun/2025)",
        "",
        f"<!-- Generated by scripts/ingest_policies.py from {PDF.name}. Do not edit by hand. -->",
    ]
    for num, title, text in sections:
        parts += ["", f"## {num}. {title}", "", text]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {len(sections)} sections to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
